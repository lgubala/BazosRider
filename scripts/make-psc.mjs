#!/usr/bin/env node
/**
 * Builds src/geo/data.js, the postal-code table behind "v okolí", from the
 * GeoNames postal code dump for Slovakia:
 *
 *   https://download.geonames.org/export/zip/SK.zip  (unzip it first)
 *   node scripts/make-psc.mjs path/to/SK.txt
 *
 * GeoNames data is licensed CC BY 4.0 (https://www.geonames.org). Every
 * postal code becomes the average position of its places, rounded to about
 * 100 m, which is plenty for "12 km away".
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) { console.log("usage: node scripts/make-psc.mjs SK.txt"); process.exit(1); }

const sums = new Map();
for (const line of readFileSync(src, "utf8").split("\n")) {
  const f = line.split("\t");
  if (f[0] !== "SK") continue;
  const psc = f[1].replace(/\s/g, "");
  const lat = Number(f[9]), lon = Number(f[10]);
  if (!/^\d{5}$/.test(psc) || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const s = sums.get(psc) || [0, 0, 0];
  sums.set(psc, [s[0] + lat, s[1] + lon, s[2] + 1]);
}

const table = {};
for (const [psc, [lat, lon, n]] of [...sums].sort()) {
  table[psc] = [Math.round((lat / n) * 1000) / 1000, Math.round((lon / n) * 1000) / 1000];
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "geo", "data.js");
writeFileSync(out,
  "/* Bazoš Rider — geo/data.js. GENERATED by scripts/make-psc.mjs, do not edit.\n" +
  " * Slovak postal code → [latitude, longitude]. Source: GeoNames\n" +
  " * (https://www.geonames.org), licensed CC BY 4.0. */\n" +
  "globalThis.BR.PSC = " + JSON.stringify(table) + ";\n");
console.log(`${Object.keys(table).length} postal codes → src/geo/data.js`);
